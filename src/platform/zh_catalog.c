int br_is_zh(void) {
    const char *language=getenv("BROGUE_LANG");
    return !language || strcmp(language,"en");
}
char *br_tr(const char *source) {
    if (!br_is_zh()) return (char*)source;
    size_t low=0, high=sizeof(catalog)/sizeof(catalog[0]);
    while(low<high) {
        size_t mid=low+(high-low)/2;
        int order=strcmp(source,catalog[mid].source);
        if(!order) return catalog[mid].translation;
        if(order<0) high=mid; else low=mid+1;
    }
    return (char*)source;
}
